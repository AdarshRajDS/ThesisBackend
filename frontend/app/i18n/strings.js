export function t(lang, key) {
  const code = lang === "de" ? "de" : "en";
  return STRINGS[code][key] ?? STRINGS.en[key] ?? key;
}

export function yesRegex(lang) {
  const pattern = t(lang, "yesPattern");
  return new RegExp(`^(${pattern})$`, "i");
}

export const STORAGE_KEY = "hfu-chat-language";

export function loadStoredLanguage() {
  if (typeof window === "undefined") return "en";
  const stored = window.localStorage.getItem(STORAGE_KEY);
  return stored === "de" ? "de" : "en";
}

export function storeLanguage(lang) {
  if (typeof window === "undefined") return;
  window.localStorage.setItem(STORAGE_KEY, lang === "de" ? "de" : "en");
}
